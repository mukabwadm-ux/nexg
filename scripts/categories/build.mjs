#!/usr/bin/env node
/**
 * Builds everything that follows from packages/contracts/src/data/category-master.json:
 *
 *   packages/booking-config/src/data/subcategory-variants.json
 *     The listed categories, renamed profiles and every subcategory that reuses a base profile.
 *   supabase/migrations/<ENUM_VERSION>_master_categories_enum.sql
 *   supabase/migrations/<DATA_VERSION>_master_categories.sql
 *     category_config rows, merchant remapping and the application registry revision.
 *
 * Run from the repo root: node scripts/categories/build.mjs
 * Re-running rewrites the three files; the migrations are idempotent.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (path) => JSON.parse(readFileSync(join(root, path), 'utf8'));

const ENUM_VERSION = '20261225000100';
const DATA_VERSION = '20261225000200';
const REGISTRY_REVISION = 'nexg-booking-2026-11-16.1';
const PREVIOUS_REGISTRY_REVISION = 'nexg-booking-2026-11-09.1';
const AUDITED_REVISION = 'nexg-booking-2026-10-31.1';

const master = read('packages/contracts/src/data/category-master.json');
const profiles = read('packages/booking-config/src/data/profiles.json');
const oldVariants = read('packages/booking-config/src/data/subcategory-variants.json').variants;
const profileById = new Map(profiles.map((p) => [p.subcategoryId, p]));
const oldVariantById = new Map(oldVariants.map((v) => [v.subcategoryId, v]));

/* ---------- checks ---------- */
const listed = new Map();
for (const category of master.categories)
  for (const sub of category.subcategories) {
    if (listed.has(sub.id)) throw new Error(`Subcategory ${sub.id} is listed twice.`);
    if (!profileById.has(sub.base))
      throw new Error(`${sub.id}: base ${sub.base} is not an audited profile.`);
    if (profileById.has(sub.id) && sub.id !== sub.base)
      throw new Error(`${sub.id} is an audited profile, so its base must be itself.`);
    listed.set(sub.id, { ...sub, categoryId: category.id });
  }
for (const id of [...profileById.keys(), ...oldVariantById.keys()])
  if (!listed.has(id) && !master.retiredSubcategories[id])
    throw new Error(`Old subcategory ${id} is neither listed nor retired.`);
for (const [from, to] of Object.entries(master.retiredSubcategories))
  if (!listed.has(to)) throw new Error(`Retired ${from} points at ${to}, which is not listed.`);

/* ---------- booking-config variants ---------- */
const variants = [];
// Old variants stay (applications already reference them); reused ones take their new name.
for (const old of oldVariants) {
  const now = listed.get(old.subcategoryId);
  variants.push(now ? { ...old, name: now.name, baseSubcategoryId: now.base } : old);
}
for (const sub of listed.values()) {
  if (sub.id === sub.base || oldVariantById.has(sub.id)) continue;
  const base = profileById.get(sub.base);
  variants.push({
    subcategoryId: sub.id,
    name: sub.name,
    categoryId: sub.categoryId,
    baseSubcategoryId: sub.base,
    specialtyNeeds: base.specialtyNeeds,
    ...(sub.group ? { group: sub.group } : {}),
  });
}
for (const v of variants) {
  const sub = listed.get(v.subcategoryId);
  if (sub?.group) v.group = sub.group;
}
const renames = {};
for (const sub of listed.values())
  if (profileById.has(sub.id) && profileById.get(sub.id).name !== sub.name)
    renames[sub.id] = sub.name;
const groups = {};
for (const sub of listed.values())
  if (sub.group && profileById.has(sub.id)) groups[sub.id] = sub.group;

writeFileSync(
  join(root, 'packages/booking-config/src/data/subcategory-variants.json'),
  JSON.stringify(
    {
      revision: REGISTRY_REVISION,
      baseRevision: AUDITED_REVISION,
      note: 'Generated by scripts/categories/build.mjs from packages/contracts/src/data/category-master.json. Do not edit by hand. `categories` is what merchants can choose, in order; every other profile stays valid for existing applications but is not offered. Each variant reuses an existing profile (baseSubcategoryId), possibly from another category, and changes only its id, name, category and description. `renames` gives audited profiles their current names.',
      categories: master.categories.map((c) => ({
        id: c.id,
        name: c.name,
        subcategoryIds: c.subcategories.map((s) => s.id),
      })),
      retiredCategories: master.retiredCategories,
      renames,
      groups,
      variants,
    },
    null,
    2,
  ) + '\n',
);

/* ---------- migrations ---------- */
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const newCategories = master.categories.filter((c) => c.new);

writeFileSync(
  join(root, `supabase/migrations/${ENUM_VERSION}_master_categories_enum.sql`),
  `-- NexG master category list (16 Nov 2026): three new merchant categories.
-- Separate from ${DATA_VERSION}_master_categories.sql because a new enum value
-- cannot be used in the transaction that adds it.
-- Generated by scripts/categories/build.mjs.

${newCategories.map((c) => `alter type public.merchant_category add value if not exists ${q(c.id)};`).join('\n')}
`,
);

const TEMPLATE = {
  games_sports: 'experiences',
  movers_relocation: 'concierge_services',
  premium_services: 'concierge_services',
};
/* Must match CATEGORY_AGREEMENT in packages/contracts/src/merchant-agreements.ts (a test checks). */
const AGREEMENT = {
  games_sports: 'experiences',
  movers_relocation: 'logistics-and-shipping',
  premium_services: 'marketplace',
};
for (const c of newCategories)
  if (!TEMPLATE[c.id] || !AGREEMENT[c.id])
    throw new Error(`New category ${c.id} needs a template and an agreement.`);
const masterRows = master.categories
  .flatMap((c, ci) =>
    c.subcategories.map(
      (s, si) =>
        `    (${q(c.id)}, ${ci + 1}, ${q(c.name)}, ${q(c.desc)}, ${si + 1}, ${q(s.id)}, ${q(s.name)}, ${s.group ? q(s.group) : 'null'}, ${q(s.base)})`,
    ),
  )
  .join(',\n');
const retiredSubRows = Object.entries(master.retiredSubcategories)
  .map(([from, to]) => `    (${q(from)}, ${q(to)})`)
  .join(',\n');
const retiredCatRows = Object.entries(master.retiredCategories)
  .map(([from, to]) => `    (${q(from)}, ${q(to)})`)
  .join(',\n');
const overrideRows = Object.entries(master.merchantOverrides)
  .map(([name, sub]) => `    (${q(name)}, ${q(sub)})`)
  .join(',\n');
const newCategoryRows = newCategories
  .map(
    (c) =>
      `    (${q(c.id)}, ${q(TEMPLATE[c.id])}, ${q(c.new.icon)}, ${q(c.new.color)}, ${q(c.new.bg)}, ${q(c.new.cardKind)}, ${q(c.new.etaStyle)})`,
  )
  .join(',\n');
const total = listed.size;

writeFileSync(
  join(root, `supabase/migrations/${DATA_VERSION}_master_categories.sql`),
  `-- NexG master category list (owner, 16 Nov 2026): 21 categories, ${total} subcategories.
--
-- Generated by scripts/categories/build.mjs from
-- packages/contracts/src/data/category-master.json. Edit that file and re-run.
--
-- 1. category_config: the 21 categories get their new names, order, description,
--    subcategory list and "What kind of business" options. Each new subcategory
--    copies its base profile's entry (fields, workflow hints) under its own id
--    and name. Games & Sports, Movers & Relocation and Premium Services &
--    Reservations are added. Health, Financial Services, Vehicle Services,
--    Flights and "Something else" are switched off. Cinemas stays under Events &
--    Experiences for the cinema seat booking.
-- 2. merchant: every merchant on a retired category or subcategory moves to the
--    one that replaces it (category, category_key and subcategory).
-- 3. merchant_application_registry: revision ${REGISTRY_REVISION}, copied from
--    ${PREVIOUS_REGISTRY_REVISION}. The taxonomy keeps every old subcategory so
--    applications in progress still validate, and adds the new ones with their
--    base profile's questions. Older revisions stay enabled.
--
-- Application payloads are history and are not rewritten.
-- Idempotent: safe to run more than once.

create temporary table _master (
  category text, category_sort int, category_label text, category_desc text,
  position int, id text, name text, grp text, base text
) on commit drop;
insert into _master values
${masterRows};

create temporary table _retired_sub (old_id text primary key, new_id text) on commit drop;
insert into _retired_sub values
${retiredSubRows};

create temporary table _retired_category (old_id text primary key, new_id text) on commit drop;
insert into _retired_category values
${retiredCatRows};

-- Every subcategory entry in category_config, from whichever category holds it.
-- A new subcategory copies its base's entry; on a re-run the base may be gone,
-- so it falls back to its own entry from the first run.
create temporary table _base_entry on commit drop as
select distinct on (e.value ->> 'id') e.value ->> 'id' as id, e.value as entry
from public.category_config cc, jsonb_array_elements(cc.subcategories) e(value)
where jsonb_typeof(cc.subcategories) = 'array'
order by e.value ->> 'id', (cc.category = e.value ->> 'categoryId') desc;

do $$
declare missing text;
begin
  select string_agg(distinct m.base, ', ') into missing
  from _master m where not exists (select 1 from _base_entry b where b.id in (m.base, m.id));
  if missing is not null then
    raise exception 'category_config has no entry for subcategories based on: %', missing;
  end if;
end $$;

-- 1a. New categories, copied from a template category.
insert into public.category_config (
  category, label, icon, card_kind, eta_style, questions, badge_rules, featured_eligible,
  extra_doc_rules, requires_ops_mapping, sort, color, bg, description, is_active,
  prep_time_required, subcategories
)
select n.category, n.category, n.icon, n.card_kind, n.eta_style, t.questions, t.badge_rules,
  t.featured_eligible, t.extra_doc_rules, t.requires_ops_mapping, 99, n.color, n.bg, '', true,
  t.prep_time_required, '[]'::jsonb
from (values
${newCategoryRows}
) n(category, template, icon, color, bg, card_kind, eta_style)
join public.category_config t on t.category = n.template
on conflict (category) do nothing;

-- 1b. Names, order, subcategories and business-type options for all 21.
with subs as (
  select m.category,
    jsonb_agg(
      b.entry || jsonb_build_object('id', m.id, 'name', m.name, 'categoryId', m.category)
        || case when m.grp is null then '{}'::jsonb else jsonb_build_object('group', m.grp) end
      order by m.position
    ) as entries,
    jsonb_agg(
      jsonb_build_object('value', m.id, 'label', m.name)
        || case when m.grp is null then '{}'::jsonb else jsonb_build_object('group', m.grp) end
      order by m.position
    ) as options,
    min(m.category_sort) as sort, min(m.category_label) as label, min(m.category_desc) as description
  from _master m
  join lateral (
    select e.entry from _base_entry e where e.id in (m.base, m.id)
    order by (e.id = m.base) desc limit 1
  ) b on true
  group by m.category
)
update public.category_config cc
set label = s.label,
  description = s.description,
  sort = s.sort,
  is_active = true,
  subcategories = s.entries || coalesce((
    select jsonb_agg(e.value) from jsonb_array_elements(cc.subcategories) e(value)
    where cc.category = 'experiences' and e.value ->> 'id' = 'cinemas'
  ), '[]'::jsonb),
  questions = case
    when jsonb_typeof(cc.questions) = 'array' then (
      select coalesce(jsonb_agg(
        case when q.value ->> 'key' = 'business_types'
          then jsonb_set(q.value, '{options}', s.options || case
            when cc.category = 'experiences' then '[{"value":"cinemas","label":"Cinemas"}]'::jsonb
            else '[]'::jsonb end)
            || case when q.value ->> 'label' ~* '^What kind of .* business do you run\\?$'
              then jsonb_build_object('label', 'What kind of ' || s.label || ' business do you run?')
              else '{}'::jsonb end
          else q.value end
        order by q.ordinality), '[]'::jsonb)
      from jsonb_array_elements(cc.questions) with ordinality q(value, ordinality)
    )
    else cc.questions end,
  updated_at = now()
from subs s
where cc.category = s.category;

-- 1c. The agreement each new category's merchants accept (interim, as in
--     packages/contracts/src/merchant-agreements.ts).
insert into public.merchant_agreement_category (category, agreement_id, interim) values
${newCategories.map((c) => `  (${q(c.id)}, ${q(AGREEMENT[c.id])}, true)`).join(',\n')}
on conflict (category) do nothing;

-- 1d. Retired categories leave every picker and public page.
update public.category_config
set is_active = false, sort = 100 + sort, updated_at = now()
where category in (select old_id from _retired_category) and is_active;

-- 1e. A merchant saved with a retired category (from an old form or script)
--     gets the replacing category as its category_key.
create or replace function public.tg_merchant_sync_category_key()
returns trigger
language plpgsql
set search_path = ''
as $fn$
begin
  if new.category_key is null
     or (tg_op = 'UPDATE'
         and new.category is distinct from old.category
         and new.category_key is not distinct from old.category_key)
  then
    new.category_key := case new.category::text
      when 'restaurant' then 'restaurants_food'
      when 'supermarket' then 'groceries_essentials'
      when 'beauty_fashion' then 'beauty'
      when 'bar_liquor' then 'alcohol_beverages'
      when 'florist' then 'flowers_gifts'
      when 'laundry' then 'laundry_cleaning'
      when 'gift_shop' then 'flowers_gifts'
      when 'airport' then 'airport_transfers'
${Object.entries(master.retiredCategories)
  .map(([from, to]) => `      when ${q(from)} then ${q(to)}`)
  .join('\n')}
      else new.category::text
    end;
  end if;
  return new;
end;
$fn$;

-- 2. Merchants on retired subcategories or categories.
create temporary table _merchant_move on commit drop as
select m.id,
  coalesce(o.new_id, l.id, r.new_id) as subcategory
from public.merchant m
left join (values
${overrideRows}
) o(trading_name, new_id) on o.trading_name = m.trading_name
  and coalesce(m.category_key, m.category::text) = 'restaurants_food'
left join _master l on l.id = m.subcategory
left join _retired_sub r on r.old_id = m.subcategory
where m.subcategory is not null;

update public.merchant m
set subcategory = mv.subcategory,
  category = (select l.category from _master l where l.id = mv.subcategory)::public.merchant_category,
  category_key = (select l.category from _master l where l.id = mv.subcategory),
  updated_at = now()
from _merchant_move mv
where mv.id = m.id and mv.subcategory is not null
  and (m.subcategory is distinct from mv.subcategory
    or coalesce(m.category_key, m.category::text) is distinct from (select l.category from _master l where l.id = mv.subcategory));

update public.merchant m
set category = r.new_id::public.merchant_category,
  category_key = r.new_id,
  updated_at = now()
from _retired_category r
where m.subcategory is null and coalesce(m.category_key, m.category::text) = r.old_id;

-- 3. Application registry revision.
insert into public.merchant_application_registry
  (revision, taxonomy, profile_questions, question_schemas, legacy_categories,
   legacy_compatibility_revision, enabled)
select ${q(REGISTRY_REVISION)},
  (
    select jsonb_object_agg(cat, ids) from (
      select cat, jsonb_agg(distinct id order by id) as ids from (
        select k.key as cat, jsonb_array_elements_text(k.value) as id
        from jsonb_each(r.taxonomy) k
        union
        select m.category, m.id from _master m
      ) all_ids group by cat
    ) per_category
  ),
  r.profile_questions || (
    select jsonb_object_agg(m.id, r.profile_questions -> m.base)
    from _master m where not (r.profile_questions ? m.id)
  ),
  r.question_schemas,
  r.legacy_categories,
  r.legacy_compatibility_revision,
  true
from public.merchant_application_registry r
where r.revision = ${q(PREVIOUS_REGISTRY_REVISION)}
on conflict (revision) do nothing;

do $$
begin
  if (select count(*) from public.category_config where is_active and category in (select category from _master)) <> 21 then
    raise exception 'Expected 21 active master categories.';
  end if;
  if exists (
    select 1 from public.category_config where is_active and category not in (select category from _master)
  ) then
    raise exception 'A category outside the master list is still active.';
  end if;
  if (select sum(jsonb_array_length(subcategories)) from public.category_config where category in (select category from _master)) <> ${total} + 1 then
    raise exception 'Expected ${total} master subcategories plus Cinemas.';
  end if;
  if exists (
    select 1 from public.merchant m
    where m.deleted_at is null and m.subcategory is not null
      and not exists (select 1 from _master l where l.id = m.subcategory)
      and m.subcategory <> 'cinemas'
  ) then
    raise exception 'A merchant is still on a retired subcategory.';
  end if;
  if not exists (
    select 1 from public.merchant_application_registry
    where revision = ${q(REGISTRY_REVISION)} and jsonb_typeof(taxonomy -> 'games_sports') = 'array'
  ) then
    raise exception 'Registry revision ${REGISTRY_REVISION} was not created.';
  end if;
end $$;
`,
);

console.log(
  `Built ${master.categories.length} categories, ${total} subcategories, ${variants.length} variants.`,
);

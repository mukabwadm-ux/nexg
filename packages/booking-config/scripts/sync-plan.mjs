import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source =
  process.env.NEXG_RECONCILED_PLAN_ROOT ||
  resolve(packageRoot, '../../docs/booking-engine/payload-reserve-plan');
const snapshots = {};
async function load(name) {
  const bytes = await readFile(resolve(source, name));
  snapshots[name] = createHash('sha256').update(bytes).digest('hex');
  return JSON.parse(bytes.toString('utf8'));
}
const questions = await load('reconciliation/effective-question-registry.json');
const profiles = await load('reconciliation/effective-profiles-128.json');
const models = await load('models.json');
const workflows = await load('reconciliation/workflow-bindings.json');
const sourceProfiles = await load('../profiles-128.json');
const taxonomy = await load('../../audits/merchant-onboarding-128-taxonomy.json');
const sourceById = new Map(sourceProfiles.profiles.map((p) => [p.subcategoryId, p]));
const categoryNames = new Map(taxonomy.rows.map((r) => [r.categoryId, r.categoryName]));
const outputQuestions = questions.questions.map((q) => ({
  id: q.questionId,
  key: q.key,
  label: q.label,
  canonicalTarget: q.canonicalTarget,
  schema: q.valueSchema,
  sourceSchema: q.sourceValueSchema,
  normalization: q.normalization,
  origin: q.origin,
  captureMode: q.captureMode,
  captureScope: q.captureScope,
  applicability: q.applicability,
  visibleWhen: q.visibleWhen,
  requiredWhen: q.requiredWhen,
  semanticValidators: q.semanticValidators || [],
}));
const compactProfiles = profiles.rows.map((p) => ({
  categoryId: p.categoryId,
  categoryName: categoryNames.get(p.categoryId),
  subcategoryId: p.subcategoryId,
  name: p.name,
  sourceWorkflowId: p.sourceWorkflowId,
  defaultModelId: p.defaultModelId,
  sourceQuestionIds: p.sourceQuestionIds,
  sourceQuestionKeys: p.sourceQuestionKeys,
  candidateModelIds: p.candidateModelIds,
  enablementGuard: p.enablementGuard,
  bindings: p.bindings.map((b) => ({
    modelId: b.modelId,
    condition: b.condition,
    requiredQuestionIds: b.requiredQuestionIds,
    composition: b.composition,
  })),
  rules: p.rules.map((r) => ({
    id: r.id,
    condition: r.condition,
    effects: r.effects,
    requiredQuestionIds: r.requiredQuestionIds,
  })),
  specialtyNeeds: p.specialtyNeeds,
  vocabulary: sourceById.get(p.subcategoryId)?.vocabulary || {},
}));
const summaries = compactProfiles.map((p) => ({
  categoryId: p.categoryId,
  categoryName: p.categoryName,
  subcategoryId: p.subcategoryId,
  name: p.name,
  defaultModelId: p.defaultModelId,
  candidateModels: p.candidateModelIds,
  specialtyNeeds: p.specialtyNeeds,
  vocabulary: p.vocabulary,
}));
const registry = {
  revision: 'nexg-booking-2026-10-31.1',
  timezone: 'Africa/Nairobi',
  questions: outputQuestions,
  aliases: questions.aliases.map((a) => ({
    sourceQuestionId: a.sourceQuestionId,
    sourceKey: a.sourceKey,
    inputPath: a.inputPath,
    targetQuestionId: a.targetQuestionId,
    scope: a.scope,
    mode: a.mode,
  })),
  componentBridges: questions.componentBridges,
  dataClassAliases: questions.dataClassInputAliases,
  dataClasses: questions.canonicalDataClasses,
  models: models.models.map((m) => ({
    id: m.id,
    requiredSetup: m.requiredSetup,
    calendar: m.calendar,
    reservationDefault: m.reservationDefault,
    resources: m.resources,
    capacityUnit: m.capacityUnit,
  })),
  intakeByModel: workflows.intakeModesByModel,
  profiles: compactProfiles,
};
await mkdir(resolve(packageRoot, 'src/data'), { recursive: true });
await writeFile(resolve(packageRoot, 'src/data/registry.json'), JSON.stringify(registry));
// Keep TypeScript from inferring a giant nested literal type from 323 schemas.
// JSON.parse reads a pinned static snapshot; no category-supplied code is evaluated.
await writeFile(
  resolve(packageRoot, 'src/data/registry.generated.ts'),
  `// Generated by scripts/sync-plan.mjs. Do not edit.\nexport default JSON.parse(${JSON.stringify(JSON.stringify(registry))}) as unknown;\n`,
);
await writeFile(resolve(packageRoot, 'src/data/profiles.json'), JSON.stringify(summaries));
await writeFile(
  resolve(packageRoot, 'src/data/provenance.json'),
  JSON.stringify(
    {
      source: 'Reconciled merchant onboarding and Payload Reserve booking contracts',
      revision: registry.revision,
      copiedOn: '2026-10-31',
      sha256: snapshots,
    },
    null,
    2,
  ) + '\n',
);
console.log(
  JSON.stringify({
    questions: outputQuestions.length,
    aliases: registry.aliases.length,
    profiles: compactProfiles.length,
    models: registry.models.length,
  }),
);

/**
 * Categories using another category's agreement until their own exists:
 * Vehicle Rentals → Vehicle Services, Health → Wellness, App Services
 * (concierge_services) → Marketplace.
 */
export const INTERIM: ReadonlySet<string> = new Set([
  'vehicle_rentals',
  'health',
  'concierge_services',
]);

const byId = new Map(MERCHANT_AGREEMENTS.map((agreement) => [agreement.id, agreement]));

export function merchantAgreement(id: string | null | undefined): MerchantAgreement | undefined {
  return id ? byId.get(id) : undefined;
}

/** The agreement a merchant in this category accepts, if the category is known. */
export function agreementForCategory(
  categoryId: string | null | undefined,
): MerchantAgreement | undefined {
  return categoryId ? merchantAgreement(CATEGORY_AGREEMENT[categoryId]) : undefined;
}

/** Where the PDF is served, opened in a new tab wherever it is linked. */
export function merchantAgreementHref(agreement: Pick<MerchantAgreement, 'id'>): string {
  return `/legal/merchant-agreements/${agreement.id}.pdf`;
}

/**
 * NexG merchant agreements: one per merchant category.
 *
 * The 18 agreements are published as PDFs in
 * apps/web/public/legal/merchant-agreements/ and accepted online during the
 * merchant application ("I have read and agree…"). This module is the one
 * place that says which agreement a category uses; the web app, the admin
 * console and the database seed (supabase/migrations/…_merchant_agreements.sql)
 * all follow it.
 *
 * The documents carry no version or date of their own, so the version is the
 * publication date plus the first 12 hex characters of the PDF's SHA-256. A
 * filled-in or revised PDF gets a new hash, hence a new version, and
 * merchants who accepted the old one can be asked to accept again. Replace
 * a PDF only together with this file and a new seed migration; a test checks
 * the hashes.
 *
 * Generated by hand from the PDFs on 2026-11-09. Three categories have no
 * agreement of their own yet and use an interim one (see INTERIM).
 */

export interface MerchantAgreement {
  /** Stable id and file name: /legal/merchant-agreements/<id>.pdf */
  id: string;
  /** "Laundry & Cleaning" in "NexG Merchant Agreement – Laundry & Cleaning". */
  title: string;
  /** Publication date + short content hash. Recorded with every acceptance. */
  version: string;
  /** SHA-256 of the published PDF. */
  sha256: string;
}


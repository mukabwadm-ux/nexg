import { readFile, realpath } from 'node:fs/promises';
import { resolve, relative, isAbsolute } from 'node:path';
import { ContractError } from '../contracts/index.js';
import { policyRegistry } from '../policy/registry.js';
import { sha256 } from '../shared/immutable.js';
import { safeRelativePath, sealRelease, type ReleaseArtifact, type ReleaseParts } from './artifact.js';
import type { ReleaseReader } from './baselineReleaseReader.js';

/**
 * The release the engine publishes since 16 Nov 2026: NexG's 22 categories and 221 subcategories, from
 * docs/discovery/MASTER_NAVIGATION.json (generated by scripts/taxonomy/build.mjs from the master list in
 * packages/contracts/src/data/category-master.json). The Discovery frontend reads the same file, so node
 * ids here are the ids the site uses.
 *
 * config/master-approval.v1.json pins the file and every icon copy it names (scripts/pin-web-icons.mjs).
 * Unlike the icon-pack baseline, a subcategory may have no icon of its own: it then draws its category's.
 * Old Discovery ids (legacy_discovery_keys) stay with the frontend's router; the engine serves current ids.
 */
interface Approval { files: { path: string; sha256: string }[] }
interface MasterNavigation {
  master_revision: string; main_category_count: number; subcategory_count: number; homepage_category_order: string[];
  categories: {
    position: number; category: string; discovery_key: string; icon_reference: string; source_category_ids: string[];
    subcategories: {
      position: number; name: string; discovery_key: string; icon_reference: string | null; source_subcategory_ids: string[];
      nested_option_candidates: { id: string; label: string; source_subcategory_ids: string[] }[];
    }[];
  }[];
}

export const masterNavigationPath = 'docs/discovery/MASTER_NAVIGATION.json';
const assetRoot = 'assets/icons-web/';
const referencePrefix = 'references/icons-v1.1/NexG_Discovery_Icons/';
function check(condition: unknown, path: string): asserts condition { if (!condition) throw new ContractError('RELEASE_INCOMPATIBLE', [path]); }

export class MasterReleaseReader implements ReleaseReader {
  #active?: Readonly<ReleaseArtifact>;
  #validated = new Map<string, Readonly<ReleaseArtifact>>();
  constructor(private readonly workspaceRoot: string) {}

  async #import(): Promise<Readonly<ReleaseArtifact>> {
    const approval = JSON.parse(await readFile(new URL('../../../config/master-approval.v1.json', import.meta.url), 'utf8')) as Approval;
    check(Array.isArray(approval.files) && approval.files.length > 0, '/approval');
    const workspace = await realpath(this.workspaceRoot);
    const contents = new Map<string, Buffer>();
    for (const file of approval.files) {
      check(safeRelativePath(file.path) && /^[a-f0-9]{64}$/.test(file.sha256) && !contents.has(file.path), '/approval');
      const path = await realpath(resolve(workspace, file.path));
      const inside = relative(workspace, path);
      check(inside && !inside.startsWith('..') && !isAbsolute(inside), file.path);
      const bytes = await readFile(path);
      check(sha256(bytes) === file.sha256, file.path);
      contents.set(file.path, bytes);
    }
    check(contents.has(masterNavigationPath), masterNavigationPath);
    const nav = JSON.parse(contents.get(masterNavigationPath)!.toString('utf8').replace(/^﻿/, '')) as MasterNavigation;

    const usedIcons = new Set<string>();
    const icon = (reference: string): string => {
      check(typeof reference === 'string' && reference.startsWith(referencePrefix) && reference.endsWith('.png'), reference);
      const path = assetRoot + reference.slice(referencePrefix.length).replace(/\.png$/, '.webp');
      check(safeRelativePath(path) && contents.has(path), path);
      usedIcons.add(path); return path;
    };

    const parts: ReleaseParts = { schemaVersion: '1', compatibility: { engineSchema: '1', rendererSchema: '1' }, nodes: [], placements: [], mappings: [], collections: [],
      assets: [], sourceFiles: structuredClone(approval.files), policy: policyRegistry, fallback: { unmapped: 'explicit_unmapped', unknownFacts: 'preserve_unknown' } };
    check(Array.isArray(nav.categories) && nav.categories.length === nav.main_category_count, '/categories');
    check(new Set(nav.categories.map(category => category.discovery_key)).size === nav.categories.length, '/categories/id');
    for (const category of nav.categories) {
      const categoryId = category.discovery_key;
      const categoryIcon = icon(category.icon_reference);
      parts.nodes.push({ id: categoryId, kind: 'category', label: category.category, order: category.position, lifecycle: 'active', assetPath: categoryIcon });
      parts.mappings.push({ nodeId: categoryId, sourceCategoryIds: [...category.source_category_ids], sourceSubcategoryIds: [],
        status: category.source_category_ids.length ? 'configured_context_only' : 'unmapped', note: 'Configured source groups are discovery context, not live item/workflow certification.' });
      check(Array.isArray(category.subcategories) && new Set(category.subcategories.map(sub => sub.discovery_key)).size === category.subcategories.length, '/subcategories');
      for (const sub of category.subcategories) {
        check(sub.discovery_key.startsWith(categoryId + ':'), '/subcategories/id');
        parts.nodes.push({ id: sub.discovery_key, kind: 'subcategory', parentId: categoryId, label: sub.name, order: sub.position, lifecycle: 'active',
          assetPath: sub.icon_reference ? icon(sub.icon_reference) : categoryIcon });
        parts.mappings.push({ nodeId: sub.discovery_key, sourceCategoryIds: [], sourceSubcategoryIds: [...sub.source_subcategory_ids],
          status: sub.source_subcategory_ids.length ? 'configured_context_only' : 'unmapped', note: `Master list ${nav.master_revision}.` });
        parts.placements.push({ id: `master:L2:${sub.discovery_key}`, surface: 'L2', contextId: categoryId, nodeId: sub.discovery_key, order: sub.position });
        /* One collection per mapped subcategory, with the id and title the frontend's catalog-group
           fallback uses (discovery/src/data/discoveryConfiguration.ts). Disabled, like the baseline's,
           until executable fact predicates exist. */
        if (sub.source_subcategory_ids.length) parts.collections.push({ id: `${categoryId}:collection:${sub.discovery_key}`, categoryId, title: sub.name,
          enabled: false, reason: 'PREDICATE_NOT_IMPLEMENTED' });
        for (const [index, option] of sub.nested_option_candidates.entries()) {
          check(option.source_subcategory_ids.every(id => sub.source_subcategory_ids.includes(id)), '/options/sourceIds');
          parts.nodes.push({ id: option.id, kind: 'option', parentId: sub.discovery_key, label: option.label, order: index + 1, lifecycle: 'context_candidate' });
          parts.mappings.push({ nodeId: option.id, sourceCategoryIds: [], sourceSubcategoryIds: [...option.source_subcategory_ids],
            status: option.source_subcategory_ids.length ? 'configured_context_only' : 'unmapped', note: 'Configured nested candidate, not a source capability.' });
        }
      }
    }
    const subCount = parts.nodes.filter(node => node.kind === 'subcategory').length;
    check(subCount === nav.subcategory_count, '/declaredCounts');
    check(new Set(nav.homepage_category_order).size === nav.homepage_category_order.length
      && nav.homepage_category_order.length === nav.categories.length, '/homepage_category_order');
    for (const [index, id] of nav.homepage_category_order.entries()) {
      check(parts.nodes.some(node => node.id === id && node.kind === 'category'), '/homepage_category_order');
      parts.placements.push({ id: `master:L1:${id}`, nodeId: id, surface: 'L1', order: index + 1 });
    }
    /* Every pinned icon is used, so the approval names nothing the release does not carry. */
    check([...contents.keys()].filter(path => path.startsWith(assetRoot)).every(path => usedIcons.has(path)), '/approval/unusedIcon');
    parts.assets = [...usedIcons].sort().map(path => ({ path, sha256: sha256(contents.get(path)!) }));
    parts.sourceFiles.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
    return sealRelease(parts, 'master');
  }

  async resolvePublishedRelease(): Promise<Readonly<ReleaseArtifact>> {
    if (!this.#active) {
      try { this.#active = await this.#import(); }
      catch (error) { if (error instanceof ContractError) throw error; throw new ContractError('RELEASE_INCOMPATIBLE', ['/masterSource']); }
      this.#validated.set(this.#active.releaseId, this.#active);
    }
    return this.#active;
  }
  async readRelease(releaseId: string): Promise<Readonly<ReleaseArtifact>> {
    await this.resolvePublishedRelease();
    const release = this.#validated.get(releaseId);
    if (!release) throw new ContractError('RELEASE_INCOMPATIBLE', ['/releaseId']);
    return release;
  }
  async refresh(): Promise<{ release: Readonly<ReleaseArtifact>; refreshed: boolean; reason?: 'RELEASE_REFRESH_REJECTED' }> {
    try {
      const next = await this.#import();
      const refreshed = next.releaseId !== this.#active?.releaseId;
      this.#active = next; this.#validated.set(next.releaseId, next);
      return { release: next, refreshed };
    } catch (error) {
      if (!this.#active) throw error;
      return { release: this.#active, refreshed: false, reason: 'RELEASE_REFRESH_REJECTED' };
    }
  }
}

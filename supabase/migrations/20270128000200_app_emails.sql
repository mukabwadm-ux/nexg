-- ══════════════════════════════════════════════════════ filling them

create function app_email.esc(p_value text)
returns text language sql immutable set search_path = '' as $$
  select replace(replace(replace(replace(replace(
    p_value, '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), '"', '&quot;'), '''', '&#39;')
$$;

create function app_email.truthy(p_value jsonb)
returns boolean language sql immutable set search_path = '' as $$
  select p_value is not null
    and p_value not in ('null'::jsonb, 'false'::jsonb, '""'::jsonb, '[]'::jsonb, '{}'::jsonb, '0'::jsonb)
$$;

/* {{ name }} for every name in a stretch with no sections left in it. */
create function app_email.fill(p_part text, p_ctx jsonb, p_html boolean)
returns text language plpgsql immutable set search_path = '' as $$
declare
  v_out text := p_part;
  v_name text;
  v_value text;
begin
  for v_name in
    select distinct (r.m)[1] from regexp_matches(p_part, '\{\{\s*([a-z0-9_]+)\s*\}\}', 'g') as r(m)
  loop
    v_value := coalesce(p_ctx ->> v_name, '');
    if p_html then
      v_value := replace(app_email.esc(v_value), E'\n', '<br>');
    end if;
    v_out := regexp_replace(v_out, '\{\{\s*' || v_name || '\s*\}\}', replace(v_value, '\', '\\'), 'g');
  end loop;
  return v_out;
end
$$;

create function app_email.render(p_template text, p_ctx jsonb, p_html boolean)
returns text language plpgsql immutable set search_path = '' as $$
declare
  v_out text := '';
  v_rest text := coalesce(p_template, '');
  v_ctx jsonb := coalesce(p_ctx, '{}'::jsonb);
  v_hash integer;
  v_caret integer;
  v_at integer;
  v_kind text;
  v_name text;
  v_close text;
  v_inner text;
  v_value jsonb;
  v_item jsonb;
begin
  loop
    v_hash := strpos(v_rest, '{{#');
    v_caret := strpos(v_rest, '{{^');
    v_at := case when v_hash = 0 then v_caret when v_caret = 0 then v_hash else least(v_hash, v_caret) end;
    exit when v_at = 0;

    v_out := v_out || app_email.fill(left(v_rest, v_at - 1), v_ctx, p_html);
    v_kind := substr(v_rest, v_at + 2, 1);
    v_rest := substr(v_rest, v_at + 3);
    v_at := strpos(v_rest, '}}');
    if v_at = 0 then
      raise exception 'An email section is not closed.' using errcode = '22023';
    end if;
    v_name := btrim(left(v_rest, v_at - 1));
    v_rest := substr(v_rest, v_at + 2);
    v_close := '{{/' || v_name || '}}';
    v_at := strpos(v_rest, v_close);
    if v_at = 0 then
      raise exception 'Email section % has no end.', v_name using errcode = '22023';
    end if;
    v_inner := left(v_rest, v_at - 1);
    v_rest := substr(v_rest, v_at + length(v_close));
    v_value := v_ctx -> v_name;

    if v_kind = '^' then
      if not app_email.truthy(v_value) then
        v_out := v_out || app_email.render(v_inner, v_ctx, p_html);
      end if;
    elsif jsonb_typeof(v_value) = 'array' then
      for v_item in select e.value from jsonb_array_elements(v_value) as e(value) loop
        v_out := v_out || app_email.render(v_inner,
          case when jsonb_typeof(v_item) = 'object' then v_ctx || v_item else v_ctx end, p_html);
      end loop;
    elsif app_email.truthy(v_value) then
      v_out := v_out || app_email.render(v_inner,
        case when jsonb_typeof(v_value) = 'object' then v_ctx || v_value else v_ctx end, p_html);
    end if;
  end loop;
  return v_out || app_email.fill(v_rest, v_ctx, p_html);
end
$$;

-- Money as the customer reads it: KES 2,050, or KES 2,050.50 when there are cents.
create function app_email.kes(p_cents bigint)
returns text language sql immutable set search_path = '' as $$
  select case
    when p_cents is null then null
    when p_cents < 0 then '− ' || app_email.kes(-p_cents)
    when p_cents % 100 = 0 then 'KES ' || to_char(p_cents / 100, 'FM999,999,999,990')
    else 'KES ' || to_char(p_cents / 100.0, 'FM999,999,999,990.00')
  end
$$;


/*
 * For a customer's receipt, the app email when its group is on. True means it
 * was queued and the plain receipt email is not needed.
 */
create function app_email.for_receipt(r public.receipt)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  p public.payment;
  v_refund public.refund;
  v_paid public.receipt;
begin
  if r.party_type <> 'guest' then
    return false;
  end if;

  if r.source_type = 'payment' then
    select * into p from public.payment where id = r.source_id;
    if p.intent = 'order' and p.order_id is not null then
      return app_email.send('11-order-placed', 'order', p.order_id,
        app_email.order_vars(p.order_id) || app_email.receipt_vars(r)
          || jsonb_build_object('total', app_email.kes(r.total_cents)),
        r.party_id, null, 'paid') is not null;
    elsif p.intent = 'stay' and p.stay_id is not null then
      return app_email.send('30-stay-confirmed', 'stay', p.stay_id,
        app_email.stay_vars(p.stay_id) || app_email.receipt_vars(r) || jsonb_build_object(
          'total', app_email.kes(r.total_cents),
          'items', (select coalesce(jsonb_agg(jsonb_build_object('quantity', 1, 'name', l ->> 'label',
                      'amount', app_email.kes((l ->> 'amount_cents')::bigint))), '[]'::jsonb)
                      from jsonb_array_elements(r.lines) l)),
        r.party_id, null, 'paid') is not null;
    end if;

  elsif r.source_type = 'refund' then
    select * into v_refund from public.refund where id = r.source_id;
    select pr.* into v_paid from public.receipt pr
      join public.payment p on p.id = pr.source_id and pr.source_type = 'payment'
     where p.order_id = v_refund.order_id and pr.party_type = 'guest'
     order by pr.issued_at desc limit 1;
    return app_email.send('13-order-refunded', 'refund', r.source_id,
      app_email.order_vars(v_refund.order_id) || jsonb_strip_nulls(jsonb_build_object(
        'receipt_number', r.number,
        'refund_amount', app_email.kes(r.total_cents),
        'refund_method', coalesce(r.method, 'your original payment'),
        'refund_timing', case r.method when 'M-Pesa' then 'It usually arrives within a few minutes.'
          when 'NexG credit' then 'It is in your NexG account now.'
          else 'Cards and banks can take up to 7 working days.' end,
        'payment_method', v_paid.method,
        'payment_reference', r.method_ref,
        'paid_at', app_email.at(r.issued_at),
        'total', app_email.kes(r.total_cents),
        'items', jsonb_build_array(jsonb_build_object('quantity', 1,
          'name', coalesce(nullif(v_refund.reason_text, ''), 'Refund'), 'amount', app_email.kes(r.total_cents))),
        'price_lines', jsonb_build_array(jsonb_build_object('label', 'Refunded', 'amount', app_email.kes(r.total_cents))))),
      r.party_id, null, 'issued') is not null;
  end if;
  return false;
exception when others then
  raise warning 'app email for receipt % not queued: %', r.number, sqlerrm;
  return false;
end
$$;

-- fn_receipt_issue as in 20261125000100, with the app email tried first for a customer.
create or replace function public.fn_receipt_issue(
  p_party_type text,
  p_party_id uuid,
  p_source_type text,
  p_source_id uuid,
  p_kind text,
  p_title text,
  p_lines jsonb,
  p_total_cents bigint,
  p_method text default null,
  p_method_ref text default null,
  p_issued_at timestamptz default now(),
  p_email boolean default true
)
returns public.receipt
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_receipt public.receipt;
  v_email text;
  v_total text;
begin
  if p_party_id is null or p_total_cents is null or p_total_cents < 0 then
    return null;
  end if;
  if exists (select 1 from public.receipt
              where source_type = p_source_type and source_id = p_source_id and party_type = p_party_type) then
    return null;
  end if;

  insert into public.receipt (
    number, kind, party_type, party_id, source_type, source_id, title, lines,
    total_cents, method, method_ref, issued_at)
  values (
    public.fn_receipt_next_number(case when p_kind = 'refund' then 'RFD' else 'RCT' end),
    p_kind, p_party_type, p_party_id, p_source_type, p_source_id, p_title,
    coalesce(p_lines, '[]'::jsonb), p_total_cents, p_method, p_method_ref,
    coalesce(p_issued_at, now()))
  returning * into v_receipt;

  perform audit.log('system'::public.actor_type, 'finance', 'receipt.issued',
    p_target_type => 'receipt', p_target_id => v_receipt.id,
    p_after => jsonb_build_object('number', v_receipt.number, 'party', p_party_type,
                                  'source', p_source_type, 'total_cents', p_total_cents));

  if p_email then
    if p_party_type = 'guest' and app_email.for_receipt(v_receipt) then
      update public.receipt set emailed_at = now() where id = v_receipt.id;
    else
      v_email := public.fn_receipt_email(p_party_type, p_party_id);
      v_total := 'KES ' || to_char(p_total_cents / 100.0, 'FM999,999,999,990.00');
      if v_email is not null then
        perform public.fn_notify_enqueue(
          'email', v_email, 'receipt',
          'Your NexG receipt ' || v_receipt.number || E'\n\n'
            || p_title || E'\n' || v_total
            || coalesce(E'\nPaid by ' || p_method, '')
            || coalesce(' · ' || p_method_ref, '') || E'\n\n'
            || 'View or print it: https://www.nexgapp.com/receipts/' || v_receipt.number || E'\n\n'
            || '— NexG Concierge',
          'Receipt ' || v_receipt.number || ' · ' || v_total,
          jsonb_build_object('receipt', v_receipt.number));
        update public.receipt set emailed_at = now() where id = v_receipt.id;
      end if;
    end if;
  end if;

  return v_receipt;
end;
$$;
revoke execute on function public.fn_receipt_issue(text, uuid, text, uuid, text, text, jsonb, bigint, text, text, timestamptz, boolean)
  from public, anon, authenticated;

-- tg_bell_becomes_email as in 20260101022500, without the order bells the
-- Orders app emails replace while that group is on.
create or replace function public.tg_bell_becomes_email()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text;
  v_staff boolean;
  v_base text;
begin
  if not exists (select 1 from public.notification_email_kind k
                  where k.kind = new.kind and k.enabled) then
    return null;
  end if;
  if new.kind in ('order.confirmed', 'order.delivered', 'order.cancelled', 'order.refunded', 'refund.issued')
     and app_email.group_on('orders') then
    return null;
  end if;

  select u.email into v_email from auth.users u where u.id = new.user_id;
  if coalesce(trim(v_email), '') = '' then return null; end if;

  select exists (select 1 from public.staff_user su where su.user_id = new.user_id) into v_staff;
  v_base := case when v_staff then 'https://admin.nexgapp.com' else 'https://nexgapp.com' end;

  perform public.fn_notify_enqueue(
    p_channel => 'email',
    p_recipient => v_email,
    p_template => 'bell_' || new.kind,
    p_subject => new.title,
    p_body => coalesce(new.body, new.title)
      || case when new.href is null then ''
              else E'\n\nOpen it: ' || v_base || new.href end
      || E'\n\n— NexG',
    p_payload => jsonb_build_object('kind', new.kind, 'notification_id', new.id),
    p_sensitive => false);
  return null;
exception when others then
  return null;
end;
$$;


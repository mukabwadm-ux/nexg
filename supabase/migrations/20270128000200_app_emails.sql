do $cron$
begin
  if not exists (select 1 from pg_extension where extname = 'pg_cron') then
    raise notice 'pg_cron is not installed here; app email reminders are not scheduled.';
    return;
  end if;
  perform cron.schedule('app-email-reminders', '17 * * * *',
    $sched$select public.cron_app_email_reminders()$sched$);
end
$cron$;

-- ═══════════════════════════════════════════════════ help from the apps

create function app_email.is_app_ticket(t public.support_ticket)
returns boolean language sql immutable set search_path = '' as $$
  select t.source_form in ('consumer_app', 'stays_app') or t.details ->> 'channel' = 'app'
$$;

create function app_email.tg_ticket()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.email is null or not app_email.is_app_ticket(new) then
    return null;
  end if;
  perform app_email.send('41-support-received', 'ticket', new.id, jsonb_strip_nulls(jsonb_build_object(
      'first_name', nullif(split_part(btrim(coalesce(new.full_name, '')), ' ', 1), ''),
      'ticket_reference', new.reference,
      'summary', left(new.body, 240))),
    new.user_id, new.email, 'received');
  return null;
exception when others then
  raise warning 'app_email.tg_ticket skipped: %', sqlerrm;
  return null;
end
$$;
create trigger support_ticket_app_email after insert on public.support_ticket
  for each row execute function app_email.tg_ticket();

create function app_email.tg_ticket_reply()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  t public.support_ticket;
  v_agent text;
begin
  if new.from_staff_id is null or new.internal then
    return null;
  end if;
  select * into t from public.support_ticket where id = new.ticket_id;
  if t.id is null or t.email is null or not app_email.is_app_ticket(t) then
    return null;
  end if;
  select nullif(split_part(btrim(su.display_name), ' ', 1), '') into v_agent
    from public.staff_user su where su.id = new.from_staff_id;
  perform app_email.send('42-support-reply', 'ticket', t.id, jsonb_build_object(
      'ticket_reference', t.reference,
      'agent_first_name', coalesce(v_agent, 'NexG'),
      'reply_text', new.body,
      'reply_preview', left(new.body, 90)),
    t.user_id, t.email, 'reply ' || new.id::text);
  return null;
exception when others then
  raise warning 'app_email.tg_ticket_reply skipped: %', sqlerrm;
  return null;
end
$$;
create trigger support_message_app_email after insert on public.support_message
  for each row execute function app_email.tg_ticket_reply();

-- ══════════════════════════════════════════ account deleted (from the app)

/* rpc_my_account_deletion_request clears requester_email as it finishes, so
   the address is the one recorded before that, and the email goes there. */
create function app_email.tg_data_request()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.kind = 'erasure' and new.channel = 'app' and new.status = 'fulfilled'
     and old.status is distinct from 'fulfilled' and old.requester_email is not null then
    perform app_email.send('52-account-deleted', 'data_request', new.id,
      jsonb_build_object('deleted_at', app_email.at(coalesce(new.fulfilled_at, now()))),
      null, old.requester_email, 'fulfilled');
  end if;
  return null;
exception when others then
  raise warning 'app_email.tg_data_request skipped: %', sqlerrm;
  return null;
end
$$;
create trigger data_request_app_email after update of status on public.data_request
  for each row execute function app_email.tg_data_request();

revoke all on all functions in schema app_email from public, anon, authenticated;

/* Check-in details once, 36 to 60 hours before. Never the codes or staff phones. */
create function app_email.reminders()
returns integer language plpgsql security definer set search_path = '' as $$
declare
  v_row record;
  v_count integer := 0;
begin
  for v_row in
    select s.id, s.guest_user_id, u.address_line, u.building, u.handoff, u.handoff_note, u.parking_note,
           u.house_rules_link, pr.house_rules
      from public.stay s
      left join public.unit u on u.id = s.unit_id
      left join public.property pr on pr.id = coalesce(s.property_id, u.property_id)
     where s.status = 'booked' and s.guest_user_id is not null
       and s.check_in between now() + interval '36 hours' and now() + interval '60 hours'
  loop
    if app_email.send('32-stay-check-in', 'stay', v_row.id, app_email.stay_vars(v_row.id) || jsonb_strip_nulls(jsonb_build_object(
        'address', nullif(concat_ws(', ', nullif(v_row.building, ''), nullif(v_row.address_line, '')), ''),
        'handoff_label', case v_row.handoff::text
          when 'guest_meets_at_gate' then 'Your host meets you at the gate'
          when 'leave_with_askari' then 'Keys with the askari'
          when 'lockbox' then 'Keys in a lockbox'
          when 'call_guest_first' then 'Your host calls you first'
          when 'reception' then 'At reception'
          when 'caretaker' then 'The caretaker lets you in'
          else 'Your host will tell you in the app' end,
        'handoff_note', nullif(v_row.handoff_note, ''),
        'parking_note', nullif(v_row.parking_note, ''),
        'house_rules', coalesce(nullif(v_row.house_rules, ''), nullif(v_row.house_rules_link, '')))),
      v_row.guest_user_id, null, 'check_in') is not null then
      v_count := v_count + 1;
    end if;
  end loop;
  return v_count;
end
$$;


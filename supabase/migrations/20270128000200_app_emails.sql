-- Customer emails for the phone apps (NexG and NexG Stays), on the email system
-- the site and portals already use. Built switched off.
--
-- Nothing new sends. Every email here goes the one way all database email goes:
-- fn_notify_enqueue -> notification_log + notification_outbox -> notify-dispatch
-- -> Resend, with the sender and an on/off switch from email_route
-- (Admin > Settings > Email routing). What this adds:
--
--   * app_email.template: the owner's designs (Consumer app docs/email-templates),
--     carried in by scripts/app-emails/sync.mjs as subject, HTML and plain text.
--     The rows come in the next migration, generated by that script.
--   * app_email.render: fills {{ value }}, {{#part}}...{{/part}} (shown when there
--     is a value; once per item for a list) and {{^part}}...{{/part}} (shown when
--     there is none). Every value is HTML-escaped in the HTML part.
--   * notification_outbox.html, sent by notify-dispatch beside the text part, and
--     nulled with the body when a message is sensitive.
--   * Six email_route rows, app_account, app_orders, app_bookings, app_stays,
--     app_support and app_privacy, all OFF. While a group is off, nothing in it is
--     queued and today's plain emails carry on unchanged. Switched on, its email
--     replaces the plain receipt and bell emails it covers: one email per event.
--   * app_email.sent: one row per email per event (a retry is a no-op), with the
--     reason when one is skipped: no address, a guest without an email, or a
--     customer who turned an optional email off. Receipts, cancellations,
--     refunds, support replies and deletion are required and never skipped for a
--     notification choice.
--   * Preview without sending: app_email.preview(key, vars) in the SQL editor, or
--     rpc_app_email_preview for staff with Settings access.
--
-- Emails and what fires them:
--   11 order placed and paid   fn_receipt_issue, an order payment settling
--   13 refund sent             fn_receipt_issue, an order refund issued
--   30 stay booked             fn_receipt_issue, a stay payment settling
--   12 order cancelled         order.stage -> cancelled
--   20 / 21 booked, reserved   app booking -> confirmed (21 for a table)
--   24 / 25 changed, cancelled app booking times moved / -> cancelled
--   26 / 27 request, price     app booking needing a quote / its price set
--   32 check-in details        hourly job, 36 to 60 hours before check-in
--   33 / 34 stay changed, cancelled
--   35 / 36 stay request received / options sent
--   41 / 42 app help request received / staff reply
--   52 account deleted         data_request erasure from the app -> fulfilled
-- A stand-in booking payment (paid_simulated) never emails. Never emailed: a
-- check-in, reservation, gate or handover code, or a staff phone number.
--
-- Rollback: select cron.unschedule('app-email-reminders'); drop the triggers
-- *_app_email; restore fn_receipt_issue (20261125000100), tg_bell_becomes_email
-- (20260101022500), fn_email_route_for (20260101022700), rpc_outbox_due and
-- rpc_outbox_sent (20260101018300); delete the six app_* email_route rows; drop
-- function public.rpc_app_email_preview, public.cron_app_email_reminders; drop
-- schema app_email cascade; alter table notification_outbox drop column html.


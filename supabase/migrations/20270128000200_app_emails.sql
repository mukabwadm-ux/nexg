/*
 * Render one email and queue it through fn_notify_enqueue. Returns the outbox
 * id, or null when nothing was queued: the group is off, there is no address,
 * the customer turned an optional email off, or this event was already sent.
 * Never raises into the change that called it.
 */
create function app_email.send(
  p_key text,
  p_subject_type text,
  p_subject_id uuid,
  p_vars jsonb,
  p_user uuid default null,
  p_email text default null,
  p_event text default ''
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  t app_email.template;
  v_to text;
  v_reason text;
  v_sent uuid;
  v_vars jsonb;
  v_outbox uuid;
begin
  select * into t from app_email.template where key = p_key;
  if t.key is null or not app_email.group_on(t.group_key) then
    return null;
  end if;

  v_to := nullif(lower(btrim(coalesce(p_email, ''))), '');
  if v_to is null and p_user is not null then
    select nullif(lower(btrim(u.email)), '') into v_to from auth.users u where u.id = p_user;
  end if;
  if v_to is null then
    v_reason := case
      when exists (select 1 from auth.users u where u.id = p_user and u.is_anonymous)
        then 'A guest without an email'
      else 'No email on file' end;
  elsif not t.required and not app_email.allowed(p_user, t.pref_category) then
    v_reason := 'The customer turned these emails off';
  end if;

  insert into app_email.sent (template_key, subject_type, subject_id, event, recipient_user, status, reason)
  values (p_key, p_subject_type, p_subject_id, coalesce(p_event, ''), p_user,
          case when v_reason is null then 'queued' else 'skipped' end, v_reason)
  on conflict (template_key, subject_type, subject_id, event) do nothing
  returning id into v_sent;
  if v_sent is null or v_reason is not null then
    return null;
  end if;

  v_vars := app_email.base_vars(p_user) || jsonb_strip_nulls(coalesce(p_vars, '{}'::jsonb));
  v_outbox := public.fn_notify_enqueue(
    p_channel => 'email',
    p_recipient => v_to,
    p_template => 'app_' || t.group_key || '.' || t.key,
    p_body => app_email.render(t.text, v_vars, false),
    p_subject => app_email.render(t.subject, v_vars, false),
    p_payload => jsonb_build_object('app_email', t.key, 'subject_type', p_subject_type,
                                    'subject_id', p_subject_id),
    p_sensitive => false);

  if v_outbox is not null then
    update public.notification_outbox set html = app_email.render(t.html, v_vars, true)
     where id = v_outbox;
  end if;
  update app_email.sent s
     set outbox_id = v_outbox,
         notification_log_id = (select o.notification_log_id from public.notification_outbox o where o.id = v_outbox),
         status = case when v_outbox is null then 'skipped' else 'queued' end,
         reason = case when v_outbox is null then 'Not queued; see notification_log' end
   where s.id = v_sent;
  return v_outbox;
exception when others then
  raise warning 'app email % not queued: %', p_key, sqlerrm;
  return null;
end
$$;

